const KEY = 'kbgraph3d.lang.v1';

export const LANGS = ['vi', 'en'];

/* Lần đầu chưa có lựa chọn: theo ngôn ngữ trình duyệt (vi → tiếng Việt, còn lại → English).
   Đã chọn tay thì tôn trọng vĩnh viễn. */
function initialLang() {
  try {
    const saved = localStorage.getItem(KEY);
    if (LANGS.includes(saved)) return saved;
  } catch (e) {}
  return (navigator.language || '').toLowerCase().startsWith('vi') ? 'vi' : 'en';
}

let LANG = initialLang();

export const lang = () => LANG;

/* Locale cho toLocaleDateString/-String. Ngày giờ CŨNG là giao diện: để 'vi-VN' cứng
   thì user chọn EN vẫn nhận định dạng Việt (audit W43 bắt 4 chỗ). Bên EN dùng en-GB
   để giữ thứ tự ngày-trước như bản Việt — en-US mm/dd đọc lệch nghĩa với cùng con số. */
export const locale = () => (LANG === 'vi' ? 'vi-VN' : 'en-GB');

export function setLang(l) {
  if (!LANGS.includes(l) || l === LANG) return;
  try { localStorage.setItem(KEY, l); } catch (e) {}
  location.reload();
}

/* t('khoá', {n: 5}) — thiếu khoá thì trả về CHÍNH khoá đó (lộ ra ngay khi nhìn màn
   hình, không im lặng nuốt mất chữ) và kêu ở console để test/dev bắt được. */
export function tr(key, vars) {
  const table = DICT[LANG] || DICT.vi;
  let s = table[key];
  if (s === undefined) {
    s = (DICT.vi[key] !== undefined) ? DICT.vi[key] : key;
    if (DICT.vi[key] === undefined) console.warn('i18n: thiếu khoá', key);
  }
  if (vars) {
    for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  }
  return s;
}

/* Áp từ điển vào markup tĩnh. Gọi lúc boot và sau mỗi lần dựng lại DOM có data-i18n.
     data-i18n       → textContent
     data-i18n-html  → innerHTML (chuỗi có thẻ inline)
     data-i18n-title → title
     data-i18n-ph    → placeholder
     data-i18n-aria  → aria-label */
export function applyI18n(root) {
  const r = root || document;
  r.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = tr(el.dataset.i18n); });
  r.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = tr(el.dataset.i18nHtml); });
  r.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = tr(el.dataset.i18nTitle); });
  r.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = tr(el.dataset.i18nPh); });
  r.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', tr(el.dataset.i18nAria)); });
  if (r === document) document.documentElement.lang = LANG;
}

/* Nút VI | EN cạnh logo — luôn thấy, một click, nhớ vĩnh viễn. */
export function initLangSwitch() {
  const box = document.getElementById('lang-sw');
  if (!box) return;
  box.innerHTML = LANGS.map(l =>
    `<button class="lang-b${l === LANG ? ' on' : ''}" data-lang="${l}" ` +
    `aria-pressed="${l === LANG}">${l.toUpperCase()}</button>`).join('');
  box.querySelectorAll('.lang-b').forEach(b => { b.onclick = () => setLang(b.dataset.lang); });
}

